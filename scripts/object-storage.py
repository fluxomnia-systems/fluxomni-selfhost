#!/usr/bin/env python3
"""Garage object-storage setup for self-hosted Fluxomni installs.

Subcommands:
  init      Generate ./object-storage/config.toml and credentials (idempotent).
  env       Print the .env assignments for the generated credentials.
  provision Create the scoped key/bucket, bound the bucket quota, and verify
            a SHA-256 checksummed object round-trip over the S3 API.
  verify-compose  Reject a rendered Compose config that weakens the
            object-storage security contract (reads JSON on stdin).

Secrets are generated locally with the `secrets` module and written with 0600
permissions. They never appear in command arguments, logs, or reports.
"""
from __future__ import annotations

import argparse
import hashlib
import hmac
import json
import os
import re
import secrets
import sys
import urllib.error
import urllib.request
from pathlib import Path

try:
    import tomllib
except ModuleNotFoundError:  # pragma: no cover - Python < 3.11
    tomllib = None

GARAGE_IMAGE = "dxflrs/garage:v2.5.0@sha256:677e5b758e4425a325b811c425c026bf35a4bf42f7ddbaa773de3f4fd779a5a5"
DEFAULT_BUCKET = "fluxomni-artifacts"
DEFAULT_QUOTA_SIZE = 10 * 1024**3  # 10 GiB
DEFAULT_QUOTA_OBJECTS = 100_000
KEY_ID_PATTERN = re.compile(r"^GK[0-9a-f]{32}$")
SECRET_PATTERN = re.compile(r"^[0-9a-f]{64}$")

CONFIG_TEMPLATE = """\
# Generated by scripts/object-storage.py. Regenerate with `object-storage.py init`.
# Single-node Garage for self-hosted Fluxomni artifact storage.
replication_factor = 1
metadata_dir = "/var/lib/garage/meta"
data_dir = "/var/lib/garage/data"
rpc_secret = "{rpc_secret}"
rpc_bind_addr = "0.0.0.0:3901"

[s3_api]
api_bind_addr = "0.0.0.0:3900"
s3_region = "us-east-1"

[admin]
api_bind_addr = "0.0.0.0:3903"
admin_token = "{admin_token}"
"""


def write_private(path: Path, value: str) -> None:
    temporary = path.with_name(f".{path.name}.{secrets.token_hex(8)}")
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    try:
        with os.fdopen(descriptor, "w") as output:
            output.write(value)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, path)
    finally:
        temporary.unlink(missing_ok=True)


def secure_dir(path: Path) -> None:
    path.mkdir(mode=0o700, exist_ok=True)
    os.chmod(path, 0o700)


def load_config(config_path: Path) -> dict:
    if tomllib is None:
        raise SystemExit("Error: provisioning requires Python 3.11+ (tomllib).")
    return tomllib.loads(config_path.read_text())


def init(directory: Path, bucket: str, quota_size: int, quota_objects: int) -> Path:
    if not re.fullmatch(r"[a-z0-9][a-z0-9-]{1,61}[a-z0-9]", bucket):
        raise SystemExit(f"Error: invalid bucket name {bucket!r}.")
    storage = directory / "object-storage"
    secure_dir(storage)
    config_path = storage / "config.toml"
    credentials_path = storage / "credentials.env"
    if config_path.exists() and credentials_path.exists():
        # Idempotent: keep existing credentials so reruns never rotate them.
        return storage
    rpc_secret = secrets.token_hex(32)
    admin_token = secrets.token_urlsafe(32)
    write_private(config_path, CONFIG_TEMPLATE.format(rpc_secret=rpc_secret, admin_token=admin_token))
    access_key = "GK" + secrets.token_hex(16)
    secret_key = secrets.token_hex(32)
    write_private(
        credentials_path,
        "\n".join(
            [
                f"FLUXOMNI_OBJECT_STORAGE_BUCKET={bucket}",
                f"FLUXOMNI_OBJECT_STORAGE_ACCESS_KEY={access_key}",
                f"FLUXOMNI_OBJECT_STORAGE_SECRET_KEY={secret_key}",
                f"FLUXOMNI_OBJECT_STORAGE_QUOTA_SIZE={quota_size}",
                f"FLUXOMNI_OBJECT_STORAGE_QUOTA_OBJECTS={quota_objects}",
                "",
            ]
        ),
    )
    return storage


def env_lines(storage: Path) -> list[str]:
    values = dict(
        line.split("=", 1)
        for line in (storage / "credentials.env").read_text().splitlines()
        if "=" in line
    )
    for key, pattern in (("FLUXOMNI_OBJECT_STORAGE_ACCESS_KEY", KEY_ID_PATTERN), ("FLUXOMNI_OBJECT_STORAGE_SECRET_KEY", SECRET_PATTERN)):
        if not pattern.fullmatch(values.get(key, "")):
            raise SystemExit(f"Error: {key} in credentials.env is damaged; regenerate with init --force.")
    return [f"{key}={values[key]}" for key in sorted(values)]


def admin_request(admin_url: str, token: str, operation: str, body: dict | None = None, query: str = "", allow_conflict: bool = False) -> dict | None:
    url = f"{admin_url}/v2/{operation}{query}"
    data = json.dumps(body).encode() if body is not None else None
    request = urllib.request.Request(url, data=data, method="POST" if data is not None else "GET")
    request.add_header("Authorization", f"Bearer {token}")
    if data is not None:
        request.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            return json.loads(response.read())
    except urllib.error.HTTPError as error:
        detail = error.read().decode(errors="replace")
        if allow_conflict and error.code == 409:
            return None  # already provisioned; idempotent rerun
        raise SystemExit(f"Error: admin API {operation} failed: {error.code} {detail}") from error


def sign_v4(method: str, url: str, access_key: str, secret_key: str, region: str, payload: bytes, headers: dict) -> dict:
    from urllib.parse import urlsplit

    parts = urlsplit(url)
    host = parts.netloc
    amz_date = headers["x-amz-date"]
    payload_hash = hashlib.sha256(payload).hexdigest()
    headers = {**headers, "host": host, "x-amz-content-sha256": payload_hash}
    signed = ";".join(sorted(headers))
    canonical_headers = "".join(f"{key}:{headers[key]}\n" for key in sorted(headers))
    canonical_request = "\n".join([method, parts.path or "/", parts.query, canonical_headers, signed, payload_hash])
    scope = f"{amz_date[:8]}/{region}/s3/aws4_request"
    string_to_sign = "\n".join(["AWS4-HMAC-SHA256", amz_date, scope, hashlib.sha256(canonical_request.encode()).hexdigest()])
    key = ("AWS4" + secret_key).encode()
    for part in (amz_date[:8], region, "s3", "aws4_request"):
        key = hmac.new(key, part.encode(), hashlib.sha256).digest()
    signature = hmac.new(key, string_to_sign.encode(), hashlib.sha256).hexdigest()
    headers["Authorization"] = (
        f"AWS4-HMAC-SHA256 Credential={access_key}/{scope}, SignedHeaders={signed}, Signature={signature}"
    )
    return headers


def s3_request(method: str, url: str, access_key: str, secret_key: str, payload: bytes = b"") -> tuple[int, bytes, dict]:
    import datetime

    now = datetime.datetime.now(datetime.UTC)
    headers = sign_v4(
        method,
        url,
        access_key,
        secret_key,
        "us-east-1",
        payload,
        {"x-amz-date": now.strftime("%Y%m%dT%H%M%SZ")},
    )
    request = urllib.request.Request(url, data=payload if method in ("PUT", "POST") else None, method=method)
    for key, value in headers.items():
        request.add_header(key, value)
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            return response.status, response.read(), dict(response.headers)
    except urllib.error.HTTPError as error:
        return error.code, error.read(), dict(error.headers)


def provision(config_path: Path, admin_url: str, s3_url: str, bucket: str, access_key: str, secret_key: str, quota_size: int, quota_objects: int) -> None:
    if not KEY_ID_PATTERN.fullmatch(access_key) or not SECRET_PATTERN.fullmatch(secret_key):
        raise SystemExit("Error: access key/secret key do not match the expected generated format.")
    config = load_config(config_path)
    token = config.get("admin", {}).get("admin_token", "")
    if not token:
        raise SystemExit("Error: config.toml has no admin token.")
    admin_request(admin_url, token, "ImportKey", {"accessKeyId": access_key, "secretAccessKey": secret_key, "name": "fluxomni"}, allow_conflict=True)
    admin_request(admin_url, token, "CreateBucket", {"globalAlias": bucket}, allow_conflict=True)
    info = admin_request(admin_url, token, "GetBucketInfo", query=f"?globalAlias={bucket}")
    bucket_id = info["id"]
    admin_request(
        admin_url,
        token,
        "AllowBucketKey",
        {"bucketId": bucket_id, "accessKeyId": access_key, "permissions": {"read": True, "write": True, "owner": False}},
    )
    admin_request(admin_url, token, "UpdateBucket", {"quotas": {"maxSize": quota_size, "maxObjects": quota_objects}}, query=f"?id={bucket_id}")
    # Verified checksums: write a probe object, read it back, compare SHA-256.
    payload = b"fluxomni-garage-probe"
    key = "provision-probe.txt"
    status, body, _ = s3_request("PUT", f"{s3_url}/{bucket}/{key}", access_key, secret_key, payload)
    if status != 200:
        raise SystemExit(f"Error: S3 probe upload failed with HTTP {status}: {body.decode(errors='replace')[:200]}")
    status, body, _ = s3_request("GET", f"{s3_url}/{bucket}/{key}", access_key, secret_key)
    if status != 200 or hashlib.sha256(body).hexdigest() != hashlib.sha256(payload).hexdigest():
        raise SystemExit("Error: S3 probe checksum mismatch; object storage is not verifying content correctly.")
    status, _, _ = s3_request("DELETE", f"{s3_url}/{bucket}/{key}", access_key, secret_key)
    if status not in (200, 204):
        raise SystemExit(f"Error: S3 probe cleanup failed with HTTP {status}.")
    print("Garage provisioned: scoped key, bucket quota, and checksummed probe verified.")


# @lat: [[installation#Object storage Compose enforcement]]
def verify_compose(config: dict) -> None:
    services = config.get("services", {})
    garage = services.get("garage")
    if garage is None:
        raise ValueError("rendered Compose config is missing the garage service")
    if garage.get("image") != GARAGE_IMAGE:
        raise ValueError("garage image must be the pinned Garage digest reference")
    for port in garage.get("ports", []):
        if str(port.get("host_ip", "")) not in ("127.0.0.1", "::1"):
            raise ValueError("garage ports must publish on loopback only")
    init = services.get("garage-init")
    if init is None:
        raise ValueError("rendered Compose config is missing the garage-init service")
    control = services.get("control-plane", {}).get("environment", {})
    backend = str(control.get("FLUXOMNI_STORAGE_BACKEND", ""))
    if "endpoint_url=http://garage:3900" not in backend or "fetch_mode=presigned" not in backend:
        raise ValueError("control-plane must use the private Garage endpoint with presigned fetches")
    rendered_key = str(control.get("AWS_ACCESS_KEY_ID", ""))
    expected_key = os.environ.get("FLUXOMNI_OBJECT_STORAGE_ACCESS_KEY", "")
    if not rendered_key or (expected_key and rendered_key != expected_key):
        raise ValueError("control-plane must use the scoped object-storage key, not ambient credentials")
    garage_env = garage.get("environment", {})
    if "GARAGE_DEFAULT_BUCKET" in garage_env or "GARAGE_DEFAULT_ACCESS_KEY" in garage_env:
        raise ValueError("garage must not use the default-bucket bootstrap; the scoped key is provisioned explicitly")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    init_parser = sub.add_parser("init", help="generate config and credentials")
    init_parser.add_argument("--dir", type=Path, required=True, help="installation directory")
    init_parser.add_argument("--bucket", default=DEFAULT_BUCKET)
    init_parser.add_argument("--quota-size", type=int, default=DEFAULT_QUOTA_SIZE)
    init_parser.add_argument("--quota-objects", type=int, default=DEFAULT_QUOTA_OBJECTS)
    env_parser = sub.add_parser("env", help="print .env assignments for generated credentials")
    env_parser.add_argument("--dir", type=Path, required=True, help="installation directory")
    provision_parser = sub.add_parser("provision", help="create scoped key/bucket and verify checksums")
    provision_parser.add_argument("--config", type=Path, required=True, help="path to object-storage/config.toml")
    provision_parser.add_argument("--admin-url", default=os.environ.get("FLUXOMNI_OBJECT_STORAGE_ADMIN_URL", "http://127.0.0.1:3903"))
    provision_parser.add_argument("--s3-url", default=os.environ.get("FLUXOMNI_OBJECT_STORAGE_S3_URL", "http://127.0.0.1:3900"))
    provision_parser.add_argument("--bucket", default=os.environ.get("FLUXOMNI_OBJECT_STORAGE_BUCKET", DEFAULT_BUCKET))
    provision_parser.add_argument("--access-key", default=os.environ.get("FLUXOMNI_OBJECT_STORAGE_ACCESS_KEY", ""))
    provision_parser.add_argument("--secret-key", default=os.environ.get("FLUXOMNI_OBJECT_STORAGE_SECRET_KEY", ""))
    provision_parser.add_argument("--quota-size", type=int, default=int(os.environ.get("FLUXOMNI_OBJECT_STORAGE_QUOTA_SIZE", DEFAULT_QUOTA_SIZE)))
    provision_parser.add_argument("--quota-objects", type=int, default=int(os.environ.get("FLUXOMNI_OBJECT_STORAGE_QUOTA_OBJECTS", DEFAULT_QUOTA_OBJECTS)))
    sub.add_parser("verify-compose", help="validate rendered Compose JSON from stdin")
    args = parser.parse_args()
    if args.command == "init":
        init(args.dir, args.bucket, args.quota_size, args.quota_objects)
    elif args.command == "env":
        print("\n".join(env_lines(args.dir / "object-storage")))
    elif args.command == "provision":
        if not args.access_key or not args.secret_key:
            raise SystemExit("Error: provision needs --access-key/--secret-key or FLUXOMNI_OBJECT_STORAGE_ACCESS_KEY/SECRET_KEY.")
        provision(args.config, args.admin_url, args.s3_url, args.bucket, args.access_key, args.secret_key, args.quota_size, args.quota_objects)
    elif args.command == "verify-compose":
        try:
            verify_compose(json.load(sys.stdin))
        except (ValueError, KeyError, TypeError) as exc:
            print(f"Error: unsafe object-storage Compose configuration: {exc}", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
